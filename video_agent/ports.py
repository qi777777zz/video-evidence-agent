"""Application ports. Tests can replace every external dependency with a fake."""
from typing import Any, Protocol


class ObjectStorage(Protocol):
    def ensure_bucket(self) -> None: ...
    def create_multipart(self, key: str, content_type: str) -> str: ...
    def presign_part(self, key: str, upload_id: str, part_number: int) -> str: ...
    def list_parts(self, key: str, upload_id: str) -> list[dict]: ...
    def complete_multipart(self, key: str, upload_id: str, parts: list[dict]) -> None: ...
    def abort_multipart(self, key: str, upload_id: str) -> None: ...
    def object_exists(self, key: str) -> bool: ...
    def object_size(self, key: str) -> int: ...
    def delete_many(self, keys: list[str]) -> None: ...
    def playback_url(self, key: str) -> str: ...
    def health(self) -> bool: ...


class WorkflowDispatcher(Protocol):
    async def dispatch_video(self, video_id: str, mode: str) -> None: ...
    async def cancel_video(self, video_id: str) -> None: ...
    async def health(self) -> bool: ...


class RateLimiter(Protocol):
    def check(self, tenant: str, operation: str, limit: int) -> None: ...
    def health(self) -> bool: ...


class AnswerModel(Protocol):
    async def answer(self, candidates: list[Any], question: str) -> dict: ...


class VectorIndex(Protocol):
    def search(self, session: Any, video_id: str, query: str) -> list[Any]: ...

